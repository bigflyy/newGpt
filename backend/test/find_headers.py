# Split the content by the delimiter
# Using regex to handle possible whitespace around the delimiter
parts = re.split(r'^--\s*Чанк\s*--$', content, flags=re.MULTILINE)

# The first part is content before the first "-- Чанк --" (if any)
# We skip it if it's just leading noise
chunks = [part.strip() for part in parts[1:] if part.strip()]

def assign_header_metadata(chunks):
    """
    Assign header metadata to each chunk based on markdown headers.
    Handles multiple headers per chunk, mid-chunk headers, and context inheritance.
    
    Args:
        chunks: List of text chunks from markdown document
    
    Returns:
        List of chunks with metadata added
    """
    current_h1 = None
    current_h2 = None
    current_h3 = None
    result = []
    
    for chunk in chunks:
        lines = chunk.split('\n')
        
        # Process each line to update header context
        for line in lines:
            stripped = line.strip()
            
            # Skip empty lines
            if not stripped:
                continue
                
            # Handle header detection (robust against extra # symbols)
            if stripped.startswith('#'):
                # Count consecutive # symbols at start
                hash_count = 0
                while hash_count < len(stripped) and stripped[hash_count] == '#':
                    hash_count += 1
                
                # Valid header must have space after hashes
                if hash_count < len(stripped) and stripped[hash_count] == ' ':
                    header_text = stripped[hash_count+1:].strip()
                    
                    if hash_count == 1:  # # Header
                        current_h1 = header_text
                        current_h2 = None
                        current_h3 = None
                    elif hash_count == 2:  # ## Header
                        current_h2 = header_text
                        current_h3 = None
                    elif hash_count == 3:  # ### Header
                        current_h3 = header_text
        
        # Capture current context AFTER processing all lines in chunk
        metadata = {}
        if current_h1 is not None:
            metadata['header1'] = current_h1
        if current_h2 is not None:
            metadata['header2'] = current_h2
        if current_h3 is not None:
            metadata['header3'] = current_h3
        
        result.append({
            'text': chunk,
            'metadata': metadata
        })
    
    return result

r = assign_header_metadata(chunks)
